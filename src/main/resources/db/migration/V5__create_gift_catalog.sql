-- Story SLE-60 / SLE-191: Persistence schema for partner merchant loyalty gifts catalog

CREATE TABLE IF NOT EXISTS loyalty_gifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    points_cost INTEGER NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    image_url VARCHAR(1000),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_loyalty_gifts_points_cost CHECK (points_cost > 0),
    CONSTRAINT chk_loyalty_gifts_stock CHECK (stock >= 0)
);

CREATE INDEX IF NOT EXISTS idx_loyalty_gifts_store_id ON loyalty_gifts (store_id);
CREATE INDEX IF NOT EXISTS idx_loyalty_gifts_store_active ON loyalty_gifts (store_id, is_active);
