-- Story SLE-45 / SLE-199: Persistence schema for User VFP status and transition audit history

CREATE TABLE IF NOT EXISTS user_vfp_status (
    user_id VARCHAR(64) PRIMARY KEY,
    is_vfp BOOLEAN NOT NULL DEFAULT FALSE,
    granted_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    last_evaluated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_user_vfp_status_is_vfp ON user_vfp_status (is_vfp);

CREATE TABLE IF NOT EXISTS user_vfp_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(32) NOT NULL,
    transaction_count INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_user_vfp_history_user_id ON user_vfp_history (user_id, created_at DESC);
