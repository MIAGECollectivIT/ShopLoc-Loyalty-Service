-- Story SLE-41 / SLE-292: Persistence schema for loyalty points holds (Click & Collect gift reservation)

CREATE TABLE IF NOT EXISTS loyalty_points_holds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid UUID NOT NULL UNIQUE,
    order_reference VARCHAR(64) NOT NULL UNIQUE,
    user_id VARCHAR(64) NOT NULL,
    total_points DECIMAL(10, 1) NOT NULL,
    status VARCHAR(32) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_loyalty_points_holds_total CHECK (total_points > 0),
    CONSTRAINT chk_loyalty_points_holds_status CHECK (status IN ('ACTIVE', 'COMMITTED', 'RELEASED'))
);

CREATE INDEX IF NOT EXISTS idx_loyalty_points_holds_user_status
    ON loyalty_points_holds (user_id, status);

CREATE TABLE IF NOT EXISTS loyalty_points_hold_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_id BIGINT NOT NULL REFERENCES loyalty_points_holds(id) ON DELETE CASCADE,
    store_uid UUID NOT NULL,
    gift_uid UUID NOT NULL,
    gift_name VARCHAR(255) NOT NULL,
    unit_points_cost INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT chk_loyalty_hold_items_cost CHECK (unit_points_cost > 0),
    CONSTRAINT chk_loyalty_hold_items_qty CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS idx_loyalty_points_hold_items_hold_id
    ON loyalty_points_hold_items (hold_id);
