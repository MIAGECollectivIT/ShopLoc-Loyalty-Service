-- Story SLE-78 / SLE-46: Persistence schema for VFP free parking sessions and acknowledgment tickets

CREATE TABLE IF NOT EXISTS vfp_parking_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    license_plate VARCHAR(32) NOT NULL,
    ticket_reference VARCHAR(64) NOT NULL UNIQUE,
    status VARCHAR(32) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    session_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_vfp_parking_user_date
    ON vfp_parking_sessions (user_id, session_date);

CREATE UNIQUE INDEX IF NOT EXISTS uq_vfp_parking_user_daily
    ON vfp_parking_sessions (user_id, session_date);
