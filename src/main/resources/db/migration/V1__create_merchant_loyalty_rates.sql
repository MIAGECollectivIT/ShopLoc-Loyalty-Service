CREATE TABLE IF NOT EXISTS merchant_loyalty_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL,
    euro_amount NUMERIC(10, 2) NOT NULL DEFAULT 1.00,
    points_reward NUMERIC(10, 1) NOT NULL DEFAULT 1.0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_merchant_loyalty_rates_store_id UNIQUE (store_id),
    CONSTRAINT chk_merchant_loyalty_rates_euro_amount CHECK (euro_amount > 0),
    CONSTRAINT chk_merchant_loyalty_rates_points_reward CHECK (points_reward >= 0.5)
);

CREATE INDEX IF NOT EXISTS idx_merchant_loyalty_rates_store_id ON merchant_loyalty_rates (store_id);

