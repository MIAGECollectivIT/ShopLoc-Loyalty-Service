-- Story SLE-38 / SLE-176: Persistence schema for customer loyalty points accounts and transactions

CREATE TABLE IF NOT EXISTS loyalty_points_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    client_code VARCHAR(32),
    balance NUMERIC(10, 1) NOT NULL DEFAULT 0.0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_loyalty_points_accounts_user_id UNIQUE (user_id),
    CONSTRAINT chk_loyalty_points_accounts_balance CHECK (balance >= 0.0)
);

CREATE TABLE IF NOT EXISTS loyalty_points_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    transaction_reference VARCHAR(64) NOT NULL,
    store_id BIGINT,
    store_name VARCHAR(255),
    type VARCHAR(32) NOT NULL,
    points NUMERIC(10, 1) NOT NULL,
    balance_after NUMERIC(10, 1) NOT NULL,
    source_type VARCHAR(32),
    description VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_loyalty_points_transactions_ref UNIQUE (transaction_reference),
    CONSTRAINT chk_loyalty_points_transactions_points CHECK (points > 0.0),
    CONSTRAINT fk_loyalty_points_tx_account
        FOREIGN KEY (account_id) REFERENCES loyalty_points_accounts (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_loyalty_points_accounts_user_id ON loyalty_points_accounts (user_id);
CREATE INDEX IF NOT EXISTS idx_loyalty_points_tx_account_id ON loyalty_points_transactions (account_id);
CREATE INDEX IF NOT EXISTS idx_loyalty_points_tx_user_id ON loyalty_points_transactions (user_id);
CREATE INDEX IF NOT EXISTS idx_loyalty_points_tx_created_at ON loyalty_points_transactions (created_at DESC);
