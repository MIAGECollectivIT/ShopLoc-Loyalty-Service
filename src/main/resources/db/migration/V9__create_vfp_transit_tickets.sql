-- Story SLE-47 / SLE-233: Persistence schema for VFP public transit tickets and external validation
CREATE TABLE IF NOT EXISTS vfp_transit_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    user_id VARCHAR(64) NOT NULL,
    ticket_reference VARCHAR(64) NOT NULL UNIQUE,
    ticket_code VARCHAR(32) NOT NULL,
    network_name VARCHAR(64) NOT NULL DEFAULT 'Réseau Urbain Collectiv''IT',
    status VARCHAR(32) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ticket_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_vfp_transit_user_date ON vfp_transit_tickets (user_id, ticket_date);
CREATE UNIQUE INDEX IF NOT EXISTS uq_vfp_transit_user_daily ON vfp_transit_tickets (user_id, ticket_date);
